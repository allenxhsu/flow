/** Glyph bitmaps: { w, rows: string[] } with rows padded to FONT_HEIGHT. */
export const FONT = Object.fromEntries(Object.entries(GLYPHS).map(([ch, s]) => {
  const rows = s.split('/');
  const w = Math.max(...rows.map((r) => r.length));
  while (rows.length < FONT_HEIGHT) rows.push('');
  return [ch, { w, rows: rows.map((r) => r.padEnd(w, '.')) }];
}));

/** The glyph for a character: accents stripped, unknown characters shown as '?'. */
export function glyphFor(ch) {
  if (FONT[ch]) return FONT[ch];
  const plain = ch.normalize('NFD').replace(/[̀-ͯ]/g, '');
  if (FONT[plain]) return FONT[plain];
  if (/\s/.test(ch)) return FONT[' '];
  if (/\p{Extended_Pictographic}|[️‍]/u.test(ch)) return null; // emoji: skipped
  return FONT['?'];
}

/** Width in pixels of a string in the font (at scale 1). */
export function measureText(str) {
  let w = 0;
  for (const ch of Array.from(String(str))) { const g = glyphFor(ch); if (g) w += g.w + 1; }
  return Math.max(0, w - 1);
}

/** Word-wrap text to a pixel width. Long words break by character. */
export function wrapText(str, width) {
  const lines = [];
  for (const para of String(str).split('\n')) {
    let line = '';
    for (const word of para.split(/ +/)) {
      const next = line ? `${line} ${word}` : word;
      if (measureText(next) <= width) { line = next; continue; }
      if (line) lines.push(line);
      line = '';
      let rest = word;
      while (measureText(rest) > width) {
        let k = rest.length;
        while (k > 1 && measureText(rest.slice(0, k)) > width) k--;
        lines.push(rest.slice(0, k));
        rest = rest.slice(k);
      }
      line = rest;
    }
    lines.push(line);
  }
  return lines;
}

/** Shorten text to fit a width, ending in '…'. */
export function fitText(str, width) {
  const s = String(str);
  if (measureText(s) <= width) return s;
  let k = s.length;
  while (k > 0 && measureText(`${s.slice(0, k)}…`) > width) k--;
  return `${s.slice(0, k).trimEnd()}…`;
}

// ─── colour helpers ─────────────────────────────────────────────────────────

/** '#rgb' or '#rrggbb' → [r, g, b], else null. */
export function parseHex(c) {
  const m = /^#?([0-9a-f]{3}|[0-9a-f]{6})$/i.exec(String(c || '').trim());
  if (!m) return null;
  let h = m[1];
  if (h.length === 3) h = h.split('').map((x) => x + x).join('');
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
}

const toHex = (rgb) => `#${rgb.map((v) => Math.max(0, Math.min(255, Math.round(v))).toString(16).padStart(2, '0')).join('')}`;

/** A darker (f < 1) or lighter (f > 1) version of a hex colour. */
export function shade(c, f) {
  const rgb = parseHex(c);
  if (!rgb) return c;
  return toHex(f <= 1 ? rgb.map((v) => v * f) : rgb.map((v) => v + (255 - v) * (f - 1)));
}

/** The colour slots for a person: hair, skin, shirt, trousers and their shades. */
export function personColors(look = {}) {
  const c = { ...HERO_DEFAULT, ...Object.fromEntries(Object.entries(look || {}).filter(([, v]) => parseHex(v))) };
  return { H: c.hair, J: shade(c.hair, 0.7), S: c.skin, K: shade(c.skin, 0.82), T: c.shirt, U: shade(c.shirt, 0.72), P: c.trousers, Q: shade(c.trousers, 0.72) };
}

/** A look for someone you meet, picked from their name so it stays the same. */
export function lookFor(name) {
  let h = 2166136261;
  for (const ch of String(name)) { h ^= ch.codePointAt(0); h = Math.imul(h, 16777619) >>> 0; }
  const pick = (list, k) => list[(h >>> k) % list.length];
  return {
    hair: pick(['#2a1c14', '#7a4a26', '#d09a48', '#1c1a2e', '#9a3a2a', '#e8e0d0'], 0),
    skin: pick(['#f0c291', '#c68a5c', '#8d5a3a', '#e5b07a'], 5),
    shirt: pick(['#c84c40', '#eb9b3f', '#8a5cc0', '#3c69b6', '#d8739c', '#56a04a'], 9),
    trousers: pick(['#3c3f5a', '#6f4630', '#2e6b40', '#4a3a6a'], 13),
    long: ((h >>> 17) & 1) === 1,
  };
}

// ─── grid helpers ───────────────────────────────────────────────────────────

export const mirror = (grid) => grid.map((r) => Array.from(r).reverse().join(''));
/** Rotate a grid a quarter turn clockwise. */
export const rotateCW = (grid) => Array.from({ length: grid[0].length }, (_, x) => grid.map((r) => r[x]).reverse().join(''));
export const rotateCCW = (grid) => Array.from({ length: grid[0].length }, (_, x) => grid.map((r) => r[r.length - 1 - x]).join(''));

/** Paint one grid over another (both the same width); '.' leaves what is below. */
export function overlay(base, top, dy = 0) {
  return base.map((row, y) => {
    const t = top[y - dy];
    if (!t) return row;
    return Array.from(row).map((c, x) => (t[x] && t[x] !== '.' ? t[x] : c)).join('');
  });
}

/** The hero's grid for a pose: direction, walk frame and outfit. */
export function heroGrid(dir = 'down', frame = 'stand', { hardHat = false, longHair = false } = {}) {
  const base = dir === 'right' ? 'left' : dir;
  let grid = [...HERO[base], ...LEGS[base][frame]];
  if (longHair && base === 'down') grid = overlay(grid, LONG_HAIR.down, 7);
  if (hardHat) grid = overlay(grid, HARD_HAT[base === 'left' ? 'left' : 'down']);
  return dir === 'right' ? mirror(grid) : grid;
}

/** The car's grid facing a direction. */
export function carGrid(dir = 'right') {
  if (dir === 'left') return mirror(CAR);
  if (dir === 'down') return rotateCW(CAR);
  if (dir === 'up') return rotateCCW(CAR);
  return CAR;
}
