/** Colour → the most common box colour in a model, for the 2D look. */
export function modelColors(boxes, carColor = '#d05050') {
  const n = new Map();
  for (const x of boxes) { const c = x[6] === '$car' ? carColor : x[6]; n.set(c, (n.get(c) || 0) + Math.abs((x[3] - x[0]) * (x[5] - x[2]))); }
  const sorted = [...n].sort((a, c) => c[1] - a[1]).map((e) => e[0]);
  const top = sorted[0] || '#c8c8c8';
  const height = Math.max(0.1, ...boxes.map((x) => x[4]));
  return { top, front: sorted[1] || top, height };
}

/** Build a THREE.Group from boxes: one shared unit box, one lit material per colour. */
export function buildModel(THREE, boxes, { carColor = '#d05050', cache = new Map() } = {}) {
  const unit = cache.get('__unit') || new THREE.BoxGeometry(1, 1, 1);
  cache.set('__unit', unit);
  const g = new THREE.Group();
  for (const [x0, y0, z0, x1, y1, z1, c0] of boxes) {
    const c = c0 === '$car' ? carColor : c0;
    if (!cache.has(c)) cache.set(c, new THREE.MeshLambertMaterial({ color: c }));
    const m = new THREE.Mesh(unit, cache.get(c));
    m.scale.set(Math.max(0.001, Math.abs(x1 - x0)), Math.max(0.001, Math.abs(y1 - y0)), Math.max(0.001, Math.abs(z1 - z0)));
    m.position.set((x0 + x1) / 2, (y0 + y1) / 2, (z0 + z1) / 2);
    g.add(m);
  }
  return g;
}
